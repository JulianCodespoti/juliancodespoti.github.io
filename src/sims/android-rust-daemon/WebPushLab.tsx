export function WebPushLab() {
  const [message, setMessage] = useState("Reply ready — 9 Vitest cases pass");
  const [stepIdx, setStepIdx] = useState(3);
  const [playing, setPlaying] = useState(false);
  const [perspective, setPerspective] = useState<Perspective>("relay");
  const [selectedField, setSelectedField] = useState<FieldKey>("cipher");

  const payload = useMemo(() => {
    const clean = message.trim() || "Reply ready";
    const utf8Len = new TextEncoder().encode(clean).length;
    return {
      clean,
      utf8Len,
      salt: fnvBytes(clean, 8, 0x11),
      rs: ["00", "00", "10", "00", "41"],
      keyid: ["04", ...fnvBytes(clean, 9, 0x77)],
      cipher: fnvBytes(clean, Math.min(18, Math.max(8, Math.ceil(utf8Len / 2))), 0xab),
      tag: fnvBytes(clean, 8, 0xef),
      totalWireBytes: 16 + 4 + 1 + 65 + utf8Len + 1 + 16,
    };
  }, [message]);

  const stepNotes = [
    `Serialize {"title":"OMP Pulse","body":"${payload.clean}"} (${payload.utf8Len} UTF-8 bytes) and append the RFC 8188 0x02 final-record delimiter.`,
    `Generate a one-shot p256::ecdh::EphemeralSecret and multiply it against the phone's subscription p256dh public key to get the 32-byte ECDH shared secret.`,
    `Run hkdf::Hkdf::<Sha256> twice: first with the phone's auth secret + "WebPush: info\\0" to derive the 32-byte IKM, then with salt[16] to derive the 16-byte CEK and 12-byte GCM nonce.`,
    `Encrypt plaintext + 0x02 with aes_gcm::Aes128Gcm using (CEK, Nonce). Zero OpenSSL symbols anywhere in the binary—identical code compiles for Linux, macOS, Windows, and Android arm64.`,
    `Sign a short-lived ES256 VAPID JWT with p256::ecdsa and POST the aes128gcm body straight to the browser's push endpoint (FCM/Mozilla/APNs). No Firebase SDK, no cloud relay of ours.`,
  ];

  const field = FIELD_INFO[selectedField];

  const blocks: { key: FieldKey; label: string; bytes: string[]; activeFromStep: number }[] = [
    { key: "salt", label: "salt[16]", bytes: payload.salt, activeFromStep: 2 },
    { key: "rs", label: "rs+len", bytes: payload.rs, activeFromStep: 3 },
    { key: "keyid", label: "as_pub[65]", bytes: payload.keyid, activeFromStep: 1 },
    { key: "cipher", label: `ciphertext[${payload.utf8Len + 1}]`, bytes: payload.cipher, activeFromStep: 3 },
    { key: "tag", label: "tag[16]", bytes: payload.tag, activeFromStep: 3 },
  ];

  return (
    <LabStage
      kicker="Lab 03 · Zero-OpenSSL Crypto"
      title="Pure-Rust RFC 8291 Web Push & VAPID Wire Inspector"
      metrics={
        <>
          <MetricPill label="Crates" value="p256 · hkdf · aes-gcm" tone="accent" />
          <MetricPill label="OpenSSL" value="0 B" tone="emerald" />
          <MetricPill label="Wire Body" value={`${payload.totalWireBytes} B`} tone="cyan" />
        </>
      }
      controls={
        <div style={{ display: "flex", flexDirection: "column", gap: "0.9rem", width: "100%" }}>
          <div style={{ display: "flex", flexWrap: "wrap", alignItems: "center", gap: "0.75rem" }}>
            <label style={{ display: "flex", alignItems: "center", gap: "0.55rem", flex: "1 1 260px" }}>
              <span style={{ fontFamily: "var(--font-mono)", fontSize: "0.74rem", color: "var(--fg-muted)", whiteSpace: "nowrap" }}>
                Notification:
              </span>
              <input
                type="text"
                value={message}
                maxLength={80}
                onChange={(e) => setMessage(e.target.value)}
                style={{
                  flex: 1,
                  minWidth: 0,
                  padding: "0.42rem 0.65rem",
                  borderRadius: "7px",
                  border: "1px solid var(--border)",
                  background: "var(--stage-bg)",
                  color: "var(--fg)",
                  fontFamily: "var(--font-mono)",
                  fontSize: "0.78rem",
                }}
              />
            </label>
            <Segmented
              label="Inspect as"
              value={perspective}
              onChange={setPerspective}
              options={[
                { value: "relay", label: "What Push Relay Sees" },
                { value: "phone", label: "What Your Phone Decrypts" },
              ]}
            />
          </div>
          <Scrubber
            steps={STEPS}
            activeIndex={stepIdx}
            onSelect={setStepIdx}
            playing={playing}
            onTogglePlay={() => setPlaying((p) => !p)}
          />
        </div>
      }
      caption={
        <>
          <strong>Step 0{stepIdx + 1} ({STEPS[stepIdx].label}):</strong> {stepNotes[stepIdx]}
        </>
      }
    >
      {/* Pipeline diagram */}
      <div
        style={{
          display: "grid",
          gridTemplateColumns: "repeat(auto-fit, minmax(125px, 1fr))",
          gap: "0.5rem",
          marginBottom: "1rem",
        }}
      >
        {[
          { step: 0, crate: "UTF-8 + 0x02", title: "Payload" },
          { step: 1, crate: "p256::ecdh", title: "Shared Secret" },
          { step: 2, crate: "hkdf + sha2", title: "CEK & Nonce" },
          { step: 3, crate: "aes-gcm", title: "aes128gcm" },
          { step: 4, crate: "p256::ecdsa", title: "VAPID JWT" },
        ].map((node) => {
          const active = node.step === stepIdx;
          const done = node.step < stepIdx;
          return (
            <button
              key={node.title}
              type="button"
              onClick={() => setStepIdx(node.step)}
              style={{
                textAlign: "left",
                padding: "0.62rem 0.72rem",
                borderRadius: "9px",
                border: `1px solid ${active ? "var(--accent)" : done ? "var(--emerald-border)" : "var(--border)"}`,
                background: active ? "var(--accent-bg)" : done ? "var(--emerald-bg)" : "var(--surface-1)",
                cursor: "pointer",
                transition: "all 150ms ease",
              }}
            >
              <div style={{ fontFamily: "var(--font-mono)", fontSize: "0.66rem", color: active ? "var(--accent-strong)" : "var(--fg-muted)" }}>
                {node.crate}
              </div>
              <div style={{ fontSize: "0.82rem", fontWeight: 600, color: "var(--fg)", marginTop: "0.18rem" }}>
                {node.title}
              </div>
            </button>
          );
        })}
      </div>

      {/* Interactive Wire Packet Inspector */}
      <div
        style={{
          padding: "0.95rem 1rem",
          borderRadius: "10px",
          border: "1px solid var(--border)",
          background: "var(--surface-1)",
        }}
      >
        <div
          style={{
            display: "flex",
            flexWrap: "wrap",
            justifyContent: "space-between",
            gap: "0.5rem",
            marginBottom: "0.7rem",
            fontFamily: "var(--font-mono)",
            fontSize: "0.72rem",
            color: "var(--fg-muted)",
          }}
        >
          <span>
            {perspective === "relay"
              ? "POST https://fcm.googleapis.com/fcm/send/… · Content-Encoding: aes128gcm"
              : "Service Worker push event · Decrypted with device private P-256 key"}
          </span>
          <span>Click any byte segment to inspect</span>
        </div>

        {perspective === "phone" && stepIdx >= 3 ? (
          <div
            style={{
              padding: "0.85rem 1rem",
              borderRadius: "8px",
              border: "1px solid var(--emerald-border)",
              background: "var(--emerald-bg)",
              fontFamily: "var(--font-mono)",
              fontSize: "0.8rem",
              color: "var(--fg)",
            }}
          >
            <div style={{ fontSize: "0.68rem", color: "var(--emerald)", marginBottom: "0.3rem" }}>
              ✓ AES-128-GCM tag verified · decrypted plaintext:
            </div>
            {`{"title": "OMP Pulse", "body": "${payload.clean}"}`}
          </div>
        ) : (
          <div style={{ display: "flex", flexWrap: "wrap", gap: "0.45rem" }}>
            {blocks.map((b) => {
              const revealed = stepIdx >= b.activeFromStep;
              const isSelected = selectedField === b.key;
              const info = FIELD_INFO[b.key];
              return (
                <button
                  key={b.key}
                  type="button"
                  onClick={() => setSelectedField(b.key)}
                  style={{
                    textAlign: "left",
                    padding: "0.45rem 0.6rem",
                    borderRadius: "7px",
                    border: `1px solid ${isSelected ? info.color : "var(--border)"}`,
                    background: isSelected ? "var(--surface-2)" : "var(--stage-bg)",
                    opacity: revealed ? 1 : 0.35,
                    cursor: "pointer",
                    fontFamily: "var(--font-mono)",
                    transition: "all 150ms ease",
                  }}
                >
                  <div style={{ fontSize: "0.66rem", color: info.color, marginBottom: "0.2rem", fontWeight: 600 }}>
                    {b.label}
                  </div>
                  <div style={{ fontSize: "0.73rem", color: "var(--fg)", letterSpacing: "0.02em" }}>
                    {b.bytes.join(" ")}…
                  </div>
                </button>
              );
            })}
          </div>
        )}

        {/* Selected field explanation */}
        <div
          style={{
            marginTop: "0.8rem",
            paddingTop: "0.7rem",
            borderTop: "1px solid var(--border-subtle)",
            display: "flex",
            flexWrap: "wrap",
            gap: "0.4rem 1.25rem",
            fontSize: "0.8rem",
            color: "var(--fg-secondary)",
          }}
        >
          {perspective === "phone" && stepIdx >= 3 ? (
            <>
              <span style={{ fontFamily: "var(--font-mono)", color: "var(--emerald)", fontWeight: 600 }}>
                Device Decryption
              </span>
              <span>
                <strong style={{ color: "var(--fg)" }}>End-to-end verified:</strong> Your phone combines its private P-256 key with <code>as_pub[65]</code> + <code>salt[16]</code> to re-derive the exact CEK and Nonce, verifies <code>auth_tag[16]</code>, and displays the alert locally.
              </span>
            </>
          ) : (
            <>
              <span style={{ fontFamily: "var(--font-mono)", color: field.color, fontWeight: 600 }}>
                {field.name} ({field.bytes})
              </span>
              <span>
                <strong style={{ color: "var(--fg)" }}>Relay visibility:</strong> {field.relaySees}. {field.note}
              </span>
            </>
          )}
        </div>
      </div>
    </LabStage>
  );
}
