type Perspective = "phone" | "relay";

function fnvBytes(input: string, len: number, saltSeed: number): string[] {
  const out: string[] = [];
  let h = (2166136261 ^ saltSeed) >>> 0;
  for (let i = 0; i < len; i++) {
    const ch = input.charCodeAt(i % Math.max(1, input.length)) || 0x42;
    h ^= (ch + i * 31) & 0xff;
    h = Math.imul(h, 16777619) >>> 0;
    out.push(((h >>> 16) & 0xff).toString(16).padStart(2, "0"));
  }
  return out;
}

